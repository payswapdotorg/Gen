/**
 * Blender codec — headless `--background --python` (priority 2).
 *
 * Declared CLI surface (Blender 3.x/4.x):
 *   blender --background --python gen_render.py -- project.json <outdir>
 * The native project artifact is a Gen JSON bundle (edit model + blender
 * extensions). The generated script drives bpy: VSE movie strips for
 * tracks/clips, keyframed fcurves for animation, the clip tracker for
 * editor.track-object, scene.render for output. The tracking op writes a
 * tracking.json artifact reporting what the headless run actually achieved —
 * never fabricated data (lock P5). .blend materialization happens inside the
 * blender run when the binary is present; without it, render fails with
 * binary-missing (never a GUI workaround).
 */

